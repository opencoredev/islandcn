/**
 * Outlines "islandcn" in Geist SemiBold into SVG path data, so the brand files
 * (lockups, the OG card) draw the wordmark without shipping a font. The site's
 * header sets the same word as live text in the system font; Geist is the
 * closest open face to it.
 *
 * Geist is under the SIL Open Font License 1.1, which exempts documents and
 * artwork made with the font. It ships in the `geist` package:
 *
 *   pnpm tsx scripts/brand/outline-wordmark.ts node_modules/geist/dist/fonts/geist-sans/Geist-SemiBold.ttf
 *
 * Writes components/brand/wordmark-data.ts. The i's round tittle comes out as
 * its own contour, so the brand can swap it for a capsule.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import opentype from "opentype.js";

const TEXT = "islandcn";
// Tracking in font units: -20 of 1000, the tight setting a semibold word takes at display sizes.
const TRACKING = -20;

const fontPath = process.argv[2];
if (fontPath === undefined) {
  throw new Error("Pass the path to Geist-SemiBold.ttf");
}

const buffer = readFileSync(resolve(fontPath));
const font = opentype.parse(buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength));
const upm = font.unitsPerEm;

interface Contour {
  readonly d: string;
  readonly minY: number;
  readonly maxY: number;
}

const round = (n: number) => Math.round(n * 10) / 10;

// opentype paths come as a flat command list. A contour starts at each "M"
// (opentype.js 2 drops the closing "Z", so a new "M" closes the last one).
const contoursOf = (path: opentype.Path): Contour[] => {
  const contours: Contour[] = [];
  let parts: string[] = [];
  let ys: number[] = [];
  const close = () => {
    if (parts.length === 0) return;
    parts.push("Z");
    contours.push({ d: parts.join(""), minY: Math.min(...ys), maxY: Math.max(...ys) });
    parts = [];
    ys = [];
  };
  for (const cmd of path.commands) {
    switch (cmd.type) {
      case "M":
        close();
        parts.push(`M${round(cmd.x)} ${round(cmd.y)}`);
        ys.push(cmd.y);
        break;
      case "L":
        parts.push(`${cmd.type}${round(cmd.x)} ${round(cmd.y)}`);
        ys.push(cmd.y);
        break;
      case "Q":
        parts.push(`Q${round(cmd.x1)} ${round(cmd.y1)} ${round(cmd.x)} ${round(cmd.y)}`);
        ys.push(cmd.y, cmd.y1);
        break;
      case "C":
        parts.push(
          `C${round(cmd.x1)} ${round(cmd.y1)} ${round(cmd.x2)} ${round(cmd.y2)} ${round(cmd.x)} ${round(cmd.y)}`,
        );
        ys.push(cmd.y, cmd.y1, cmd.y2);
        break;
      case "Z":
        close();
        break;
      default: {
        const _exhaustive: never = cmd;
        throw new Error(`Unknown path command ${String(_exhaustive)}`);
      }
    }
  }
  close();
  return contours;
};

const baseline = font.ascender;
let x = 0;
const glyphs = [...TEXT].map((char) => {
  const glyph = font.charToGlyph(char);
  const path = glyph.getPath(x, baseline, upm);
  const box = path.getBoundingBox();
  const advance = glyph.advanceWidth ?? upm * 0.6;
  const out = { char, contours: contoursOf(path), x1: box.x1, x2: box.x2, y1: box.y1, y2: box.y2 };
  x += advance + TRACKING;
  return out;
});

const minX = Math.min(...glyphs.map((g) => g.x1));
const maxX = Math.max(...glyphs.map((g) => g.x2));
const minY = Math.min(...glyphs.map((g) => g.y1));
const maxY = Math.max(...glyphs.map((g) => g.y2));

// The tittle is the i's topmost contour; everything else is the body.
const first = glyphs[0];
if (first === undefined || first.char !== "i") {
  throw new Error("Expected the wordmark to start with i");
}
const byTop = [...first.contours].sort((a, b) => a.minY - b.minY);
const tittle = byTop[0];
if (tittle === undefined || byTop.length < 2) {
  throw new Error("Expected the i to have a separate tittle contour");
}
const body = glyphs.flatMap((g) => g.contours.filter((c) => c !== tittle).map((c) => c.d)).join("");
const stemTop = Math.min(...first.contours.filter((c) => c !== tittle).map((c) => c.minY));

const data = {
  font: "Geist SemiBold (SIL OFL 1.1)",
  unitsPerEm: upm,
  tracking: TRACKING,
  viewBox: [round(minX), round(minY), round(maxX - minX), round(maxY - minY)],
  baseline: round(baseline),
  xHeight: round(baseline - (font.tables.os2?.sxHeight ?? 0)),
  body,
  tittle: { d: tittle.d, top: round(tittle.minY), bottom: round(tittle.maxY) },
  i: { x1: round(first.x1), x2: round(first.x2), stemTop: round(stemTop) },
};

const out = `// Generated by scripts/brand/outline-wordmark.ts from ${data.font}. Do not edit by hand.
export const WORDMARK_DATA = ${JSON.stringify(data, null, 2)} as const;
`;
writeFileSync(resolve("components/brand/wordmark-data.ts"), out);
console.log(JSON.stringify({ ...data, body: `${body.length} chars` }, null, 2));
